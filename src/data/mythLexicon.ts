export const EXTRA_LEXICON: Record<string, WordEntry> = {};

export function registerExtraWords(entries: Record<string, WordEntry>): void {
  Object.assign(EXTRA_LEXICON, entries);
}

function guessGrammarNote(word: string): string {
  if (word.endsWith('bant') || word.endsWith('bat')) return 'imperfect active';
  if (word.endsWith('erunt') || word.endsWith('avit') || word.endsWith('ivit')) return 'perfect active';
  if (word.endsWith('isset') || word.endsWith('issent')) return 'pluperfect subjunctive';
  if (word.endsWith('arent') || word.endsWith('erent') || word.endsWith('eret') || word.endsWith('iret')) return 'imperfect subjunctive';
  if (word.endsWith('issimus') || word.endsWith('issima') || word.endsWith('issimum')) return 'superlative';
  return '';
}

export function lookupLatinWordMeaning(rawToken: string): WordEntry {
  const clean = rawToken.replace(/[^A-Za-z]/g, '');
  const lower = clean.toLowerCase();

  if (EXTRA_LEXICON[lower]) return EXTRA_LEXICON[lower];
  if (EXACT_WORDS[lower]) return EXACT_WORDS[lower];

  // Handle -que ("and") enclitic when not an exact dictionary word
  if (lower.endsWith('que') && lower.length > 5) {
    const base = lower.slice(0, -3);
    const baseRes = lookupLatinWordMeaning(base);
    return {
      headword: baseRes.headword + ' + -que',
      meaning: 'and ' + baseRes.meaning
    };
  }

  for (const entry of SORTED_STEMS) {
    if (lower.startsWith(entry.stem)) {
      const note = guessGrammarNote(lower);
      return {
        headword: entry.headword,
        meaning: note ? `${entry.meaning} (${note})` : entry.meaning
      };
    }
  }

  // Fallback for capitalized proper nouns not explicitly listed
  if (clean && clean[0] === clean[0].toUpperCase()) {
    return {
      headword: clean,
      meaning: 'classical name / proper noun'
    };
  }

  return {
    headword: clean || rawToken,
    meaning: 'Latin word in passage'
  };
}

